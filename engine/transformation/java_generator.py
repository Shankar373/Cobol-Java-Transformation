"""Java code generator from Java Application IR.

Generates native Java source code from a JavaApplication IR.
The generated Java:
- Uses only standard Java libraries (java.io, java.util)
- Reads actual workload input files
- Produces the same output artifacts as the source program
- Has no COBOL runtime dependency
- Is a genuine standalone Java application

Every program is generated from its lowered statements (the mapping layer's
statement lowering). The former heuristic "decision" and "file_io" template
lanes, and the CobolProgram-based generator behind them, were removed in the
2026-11-03 audit (T5): a template could replace the lowered statements and
drop whatever it did not model.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from engine.transformation.java_render import JavaSourceRenderer
from engine.transformation.java_ir import (
    JavaApplication,
    JavaClass,
    JavaProgram,
)


@dataclass
class GeneratedFile:
    """A generated Java source file."""
    filename: str
    source_code: str
    class_name: str


class JavaGenerator(JavaSourceRenderer):
    """Generates Java source from Java Application IR.

    Statement/expression rendering is the shared ``JavaSourceRenderer``
    (``engine/transformation/java_render.py``, audit C1); this generator
    strips the outer group of ``if`` conditions.

    Primary entry point: generate_from_java(application: JavaApplication)
    Backward-compatible: generate(program: CobolProgram) via mapping adapter.
    """

    strip_if_condition_parens = True
    render_throw = True


    def generate_from_java(self, application: JavaApplication) -> list[GeneratedFile]:
        """Generate Java source from JavaApplication IR.

        This is the primary entry point. The generator knows nothing about COBOL.
        For multi-program applications, generates:
        - One Java file per program
        - A service registry class for cross-program references
        """
        files: list[GeneratedFile] = []

        # Generate one file per program
        for program in application.programs:
            class_name = self._to_java_class_name(program.program_id)
            # Every program goes through statement lowering. The heuristic
            # "decision" and "file_io" template lanes were removed (audit T5):
            # they could replace the lowered statements with a positional
            # template and dropped what the template did not model.
            source = self._generate_minimal_java_from_ir(program, class_name)

            files.append(GeneratedFile(
                filename=f"{class_name}.java",
                source_code=source,
                class_name=class_name,
            ))

        # Generate service registry for multi-program applications
        if len(application.programs) > 1:
            registry_source = self._generate_service_registry(application)
            files.append(GeneratedFile(
                filename="ServiceRegistry.java",
                source_code=registry_source,
                class_name="ServiceRegistry",
            ))

        return files

    def _generate_service_registry(self, application: JavaApplication) -> str:
        """Generate a service registry class for cross-program references.

        Creates a simple registry that allows programs to call each other.
        """
        lines = [
            "import java.util.HashMap;",
            "import java.util.Map;",
            "",
            "/**",
            f" * Service registry for application: {application.application_id}",
            " * Auto-generated by COBOL-to-Java transformer.",
            " */",
            "public class ServiceRegistry {",
            "",
            "    private static final ServiceRegistry INSTANCE = new ServiceRegistry();",
            "    private final Map<String, Object> services = new HashMap<>();",
            "",
            "    private ServiceRegistry() {}",
            "",
            "    public static ServiceRegistry getInstance() {",
            "        return INSTANCE;",
            "    }",
            "",
            "    public <T> void register(String name, T service) {",
            "        services.put(name, service);",
            "    }",
            "",
            "    @SuppressWarnings(\"unchecked\")",
            "    public <T> T get(String name) {",
            "        return (T) services.get(name);",
            "    }",
            "",
        ]

        # Add method stubs for each program's entry point
        for program in application.programs:
            class_name = self._to_java_class_name(program.program_id)
            lines.extend([
                f"    /** Call {class_name}. */",
                f"    public void call{class_name}() {{",
                f"        {class_name} program = get(\"{class_name}\");",
                "        if (program != null) {",
                "            // program execution placeholder",
                "        }",
                "    }",
                "",
            ])

        lines.append("}")
        return "\n".join(lines)

    def generate(self, program: Any) -> list[GeneratedFile]:
        """Backward-compatible entry point: CobolProgram → Java source.

        Uses the mapping layer to convert CobolProgram → JavaApplication,
        then delegates to generate_from_java.
        """
        from engine.transformation.cobol_to_java_mapping import (
            map_cobol_program_to_java,
        )
        from engine.transformation.java_ir import JavaApplication

        java_program = map_cobol_program_to_java(program)
        application = JavaApplication(
            application_id=program.program_id,
            programs=(java_program,),
        )
        return self.generate_from_java(application)

    def _to_java_class_name(self, cobol_name: str) -> str:
        return cobol_name.replace("-", "_").replace(" ", "_").title()

    # ================================================================
    # IR-DRIVEN GENERATION METHODS (no COBOL knowledge)
    # ================================================================

    def _generate_minimal_java_from_ir(self, program: JavaProgram, class_name: str) -> str:
        """Generate Java for minimal programs from JavaProgram IR."""
        java_class = program.java_class
        if not java_class:
            raise ValueError("MISSING_REQUIRED_SEMANTIC: No Java class in program.")

        declarations = self._gen_field_declarations_from_ir(java_class)

        # Collect all method bodies (all non-main methods) and main body
        all_methods_src: list[str] = []
        main_body = ""
        uses_file_write = False
        uses_cobol_file_io_stmt = False
        uses_cobol_stdin_stmt = False
        uses_cobol_inspect_stmt = False
        uses_cobol_sql_stmt = False
        uses_cobol_sort_stmt = False
        uses_cobol_flow_stmt = False

        for method in java_class.methods:
            method_stmts: list[str] = []
            for stmt in method.body_statements:
                stmt_str = self._stmt_to_string(stmt)
                if stmt_str:
                    method_stmts.append(stmt_str)
                    if "_FileWriteHelper" in stmt_str:
                        uses_file_write = True
                    if "CobolFileIo." in stmt_str:
                        uses_cobol_file_io_stmt = True
                    if "CobolStdin." in stmt_str:
                        uses_cobol_stdin_stmt = True
                    if "CobolInspect." in stmt_str:
                        uses_cobol_inspect_stmt = True
                    if "CobolSql." in stmt_str:
                        uses_cobol_sql_stmt = True
                    if "CobolSort." in stmt_str:
                        uses_cobol_sort_stmt = True
                    if "CobolFlow." in stmt_str:
                        uses_cobol_flow_stmt = True

            if method.name == "main":
                main_body = "".join(f"        {s}\n" for s in method_stmts)
            else:
                params = ", ".join(
                    f"{self._java_type_to_string(p.java_type)} {p.name}"
                    for p in method.parameters
                )
                throws = " throws Exception" if method.exceptions else ""
                body = "".join(f"        {s}\n" for s in method_stmts)
                mods = " ".join(method.modifiers) if method.modifiers else "public static"
                ret = self._java_type_to_string(method.return_type) if method.return_type else "void"
                all_methods_src.append(
                    f"\n    {mods} {ret} {method.name}({params}){throws} {{\n{body}    }}\n"
                )

        extra_methods = "".join(all_methods_src)

        file_write_helper = ""
        file_write_imports = ""
        support_code = ""
        # CobolSort reads and writes its files through CobolFileIo, so a SORT needs it too
        uses_cobol_file_io = uses_file_write or uses_cobol_file_io_stmt or uses_cobol_sort_stmt
        if uses_cobol_file_io:
            from engine.transformation.file_io_support_template import COBOL_FILE_IO_JAVA
            support_code = "\n" + COBOL_FILE_IO_JAVA + "\n"
        if uses_cobol_stdin_stmt:
            # ACCEPT lowering references the shared CobolStdin helper;
            # emit it next to the program class (same pattern as
            # CobolFileIo) so the output always compiles standalone.
            from engine.transformation.stdin_support_template import COBOL_STDIN_JAVA
            support_code += "\n" + COBOL_STDIN_JAVA + "\n"
        if uses_cobol_inspect_stmt:
            from engine.transformation.inspect_support_template import COBOL_INSPECT_JAVA
            support_code += "\n" + COBOL_INSPECT_JAVA + "\n"
        if uses_cobol_sql_stmt:
            from engine.transformation.sql_support_template import COBOL_SQL_JAVA
            support_code += "\n" + COBOL_SQL_JAVA + "\n"
        if uses_cobol_sort_stmt:
            from engine.transformation.sort_support_template import COBOL_SORT_JAVA
            support_code += "\n" + COBOL_SORT_JAVA + "\n"
        if uses_cobol_flow_stmt:
            from engine.transformation.flow_support_template import COBOL_FLOW_JAVA
            support_code += "\n" + COBOL_FLOW_JAVA + "\n"
        if uses_file_write:
            file_write_imports = (
                "import java.io.FileWriter;\n"
                "import java.io.PrintWriter;\n"
            )
            file_write_helper = (
                "\n"
                "    /** Append a text line to a file (sequential WRITE). */\n"
                "    static void _FileWriteHelper_appendLine(String path, String line) throws Exception {\n"
                "        try (PrintWriter _pw = new PrintWriter(new FileWriter(path, true))) {\n"
                "            _pw.println(line);\n"
                "        }\n"
                "    }\n"
            )
            # Rewrite _FileWriteHelper.appendLine calls to use the actual method name
            main_body = main_body.replace(
                "_FileWriteHelper.appendLine(", "_FileWriteHelper_appendLine("
            )
            extra_methods = extra_methods.replace(
                "_FileWriteHelper.appendLine(", "_FileWriteHelper_appendLine("
            )

        return f'''{file_write_imports}import java.io.PrintStream;

public class {class_name} {{
{declarations}
{extra_methods}
    public static void main(String[] args) throws Exception {{
        PrintStream out = System.out;
{main_body}    }}{file_write_helper}{support_code}}}
'''

    # ================================================================
    # IR-DRIVEN HELPER METHODS
    # ================================================================

    def _java_type_to_string(self, java_type) -> str:
        """Render a JavaType to its Java source string using the canonical renderer."""
        if java_type is None:
            return "void"
        try:
            return java_type.to_source()
        except Exception:
            return "void"

    def _gen_field_declarations_from_ir(self, java_class: JavaClass) -> str:
        """Generate Java variable declarations from JavaClass fields."""
        lines = []
        for field in java_class.fields:
            type_str = field.java_type.to_source()
            if field.initializer is not None:
                # Render through the literal renderer so String
                # initializers are always quoted (never bare identifiers).
                default = self._expr_to_string(field.initializer)
            elif type_str == "int":
                default = "0"
            elif type_str == "String":
                default = '""'
            else:
                default = "0"
            lines.append(f'    static {type_str} {field.name} = {default};')
        return "\n".join(lines)
